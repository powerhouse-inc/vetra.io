/** "secret · set 3 days ago by Frank" / "set 3 days ago by Frank". */
function SetBy({ setting }: { setting: AppSetting }) {
  return (
    <span title={formatTimestamp(setting.updatedAt)}>
      set {timeAgo(setting.updatedAt)} by <PersonName value={setting.updatedBy} />
    </span>
  )
}

function SettingRow({
  setting,
  onReplace,
  onDelete,
}: {
  setting: AppSetting
  onReplace: () => void
  onDelete: () => void
}) {
  return (
    <li
      data-testid={`setting-${setting.name}-${setting.scope}`}
      className="flex flex-col gap-2 px-4 py-3 sm:flex-row sm:items-center sm:gap-4"
    >
      <div className="min-w-0 sm:w-64 sm:shrink-0">
        <p className="truncate font-mono text-sm font-medium" title={setting.name}>
          {setting.name}
        </p>
        <p className="text-muted-foreground text-xs">{SCOPE_LABEL[setting.scope]}</p>
      </div>
      <div className="min-w-0 flex-1 text-xs">
        {setting.secret ? (
          <p className="text-muted-foreground inline-flex flex-wrap items-center gap-1">
            <Lock className="h-3 w-3 shrink-0" aria-hidden />
            <span>secret ·</span>
            <SetBy setting={setting} />
          </p>
        ) : (
          <>
            <p className="truncate font-mono text-sm" title={setting.value ?? ''}>
              {setting.value ? (
                setting.value
              ) : (
                <span className="text-muted-foreground italic">empty</span>
              )}
            </p>
            <p className="text-muted-foreground">
              <SetBy setting={setting} />
            </p>
          </>
        )}
      </div>
      <div className="flex shrink-0 gap-1">
        <Button size="sm" variant="ghost" onClick={onReplace}>
          <Pencil className="h-3.5 w-3.5" />
          Replace
        </Button>
        <Button
          size="sm"
          variant="ghost"
          onClick={onDelete}
          aria-label={`Delete ${setting.name} (${SCOPE_LABEL[setting.scope].toLowerCase()})`}
          className="text-destructive hover:text-destructive"
        >
          <Trash2 className="h-3.5 w-3.5" />
        </Button>
      </div>
    </li>
  )
}

function VetraRow({ setting }: { setting: VetraInstanceSetting }) {
  return (
    <li
      data-testid={`vetra-${setting.name}`}
      className="flex flex-col gap-1 px-4 py-2.5 sm:flex-row sm:items-center sm:gap-4"
    >
      <span className="truncate font-mono text-sm sm:w-64 sm:shrink-0" title={setting.name}>
        {setting.name}
      </span>
      {setting.secret ? (
        <span className="text-muted-foreground inline-flex min-w-0 items-center gap-1 text-xs">
          <Lock className="h-3 w-3 shrink-0" aria-hidden />
          <span className="truncate">generated by Vetra · {setting.value}</span>
        </span>
      ) : (
        <span className="text-muted-foreground min-w-0 truncate text-xs">{setting.value}</span>
      )}
    </li>
  )
}

type Editing = { mode: 'add' } | { mode: 'replace'; setting: AppSetting }

/**
 * Add or replace one setting. A secret's value is write-only: the field is never prefilled, so
 * replacing a secret means typing a new value.
 */
export function SettingDialog({
  appId,
  editing,
  data,
  onClose,
}: {
  appId: string
  editing: Editing
  data: AppSettings
  onClose: () => void
}) {
  const replacing = editing.mode === 'replace' ? editing.setting : null
  const [name, setName] = useState(replacing?.name ?? '')
  const [scope, setScope] = useState<AppSettingScope>(replacing?.scope ?? 'ALL')
  const [secret, setSecret] = useState(replacing?.secret ?? false)
  const [value, setValue] = useState(replacing && !replacing.secret ? (replacing.value ?? '') : '')
  const [touched, setTouched] = useState(false)
  const [serverError, setServerError] = useState<string | null>(null)
  const set = useSetAppSetting(appId)

  const nameError = replacing ? null : settingNameError(name, data)
  const valueError = settingValueError(name, value, secret)
  const existing = replacing
    ? null
    : data.settings.find((s) => s.name === name && s.scope === scope)
  const full = !replacing && !existing && data.settings.length >= MAX_SETTINGS_PER_APP
  const invalid = !!nameError || !!valueError || full

  const submit = (e: React.FormEvent) => {
    e.preventDefault()
    setTouched(true)
    if (invalid) return
    setServerError(null)
    set.mutate(
      { name, value, secret, scope },
      {
        onSuccess: () => {
          toast.success(`${name} saved. Instances pick it up on their next rollout.`)
          onClose()
        },
        onError: (err) => setServerError(describeAppsError(err)),
      },
    )
  }

  const showNameError = !!nameError && (touched || name.length > 0)
  const showValueError = !!valueError && (touched || value.length > 0)

  return (
    <Dialog open onOpenChange={(open) => !open && !set.isPending && onClose()}>
      <DialogContent>
        <form onSubmit={submit} className="grid gap-5" noValidate>
          <DialogHeader>
            <DialogTitle>{replacing ? `Replace ${replacing.name}` : 'Add a setting'}</DialogTitle>
            <DialogDescription>
              {replacing?.secret
                ? 'Secrets are never shown again. Type the new value to replace it.'
                : 'Every instance in the scope restarts with the new value.'}
            </DialogDescription>
          </DialogHeader>

          <div className="space-y-2">
            <Label htmlFor="setting-name">Name</Label>
            <Input
              id="setting-name"
              value={name}
              disabled={!!replacing}
              onChange={(e) => setName(e.target.value)}
              placeholder="API_BASE_URL"
              className="font-mono"
              autoComplete="off"
              spellCheck={false}
              aria-invalid={showNameError}
              aria-describedby="setting-name-hint"
            />
            <p
              id="setting-name-hint"
              className={
                showNameError ? 'text-destructive text-xs' : 'text-muted-foreground text-xs'
              }
            >
              {showNameError ? nameError : 'Capitals, digits and _, starting with a capital.'}
            </p>
          </div>

          <div className="flex items-center justify-between gap-4 rounded-lg border p-3">
            <div className="space-y-0.5">
              <Label htmlFor="setting-secret">Secret</Label>
              <p className="text-muted-foreground text-xs">
                Stored encrypted and never shown again. Use it for keys, tokens and passwords.
              </p>
            </div>
            <Switch
              id="setting-secret"
              checked={secret}
              onCheckedChange={(checked) => {
                setSecret(checked)
                // A plain value typed so far must not linger in a secret field, nor the reverse.
                setValue('')
              }}
            />
          </div>

          <div className="space-y-2">
            <Label htmlFor="setting-value">{secret ? 'Secret value' : 'Value'}</Label>
            {secret ? (
              <Input
                id="setting-value"
                type="password"
                value={value}
                onChange={(e) => setValue(e.target.value)}
                autoComplete="new-password"
                spellCheck={false}
                placeholder={replacing?.secret ? 'Type a new value' : undefined}
                aria-invalid={showValueError}
                className="font-mono"
              />
            ) : (
              <Textarea
                id="setting-value"
                value={value}
                onChange={(e) => setValue(e.target.value)}
                spellCheck={false}
                rows={2}
                aria-invalid={showValueError}
                className="font-mono text-sm"
              />
            )}
            {showValueError && <p className="text-destructive text-xs">{valueError}</p>}
            {!secret && !showValueError && (
              <p className="text-muted-foreground text-xs">
                Plain values are visible in Vetra&apos;s deployment repository.
              </p>
            )}
          </div>

          <fieldset className="space-y-2" disabled={!!replacing}>
            <legend className="mb-2 text-sm font-medium">Applies to</legend>
            <RadioGroup
              value={scope}
              onValueChange={(v) => setScope(v as AppSettingScope)}
              className="gap-2"
            >
              {SETTING_SCOPES.map((s) => (
                <label
                  key={s}
                  htmlFor={`setting-scope-${s}`}
                  className="flex cursor-pointer items-start gap-3 rounded-lg border p-3 text-sm has-[:disabled]:cursor-default has-[:disabled]:opacity-70"
                >
                  <RadioGroupItem id={`setting-scope-${s}`} value={s} className="mt-0.5" />
                  <span className="space-y-0.5">
                    <span className="block font-medium">{SCOPE_LABEL[s]}</span>
                    <span className="text-muted-foreground block text-xs">{SCOPE_HINT[s]}</span>
                  </span>
                </label>
              ))}
            </RadioGroup>
          </fieldset>

          {existing && (
            <p className="text-muted-foreground text-xs">
              {name} already has a value for {SCOPE_LABEL[scope].toLowerCase()}; saving replaces it.
            </p>
          )}
          {full && (
            <p role="alert" className="text-destructive text-xs">
              An app has at most {MAX_SETTINGS_PER_APP} settings; delete one first.
            </p>
          )}
          {serverError && (
            <p role="alert" className="text-destructive text-sm">
              {serverError}
            </p>
          )}

          <DialogFooter>
            <Button type="button" variant="ghost" onClick={onClose} disabled={set.isPending}>
              Cancel
            </Button>
            <Button type="submit" disabled={set.isPending || (touched && invalid)}>
              {set.isPending && <Loader2 className="h-4 w-4 animate-spin" />}
              {replacing ? 'Replace' : 'Add setting'}
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  )
}

function DeleteSettingDialog({
  appId,
  setting,
  onClose,
}: {
  appId: string
  setting: AppSetting
  onClose: () => void
}) {
  const del = useDeleteAppSetting(appId)
  const onDelete = () =>
    del.mutate(
      { name: setting.name, scope: setting.scope },
      {
        onSuccess: () => {
          toast.success(`${setting.name} deleted`)
          onClose()
        },
        onError: (err) => toast.error(describeAppsError(err)),
      },
    )
  return (
    <AlertDialog open onOpenChange={(open) => !open && !del.isPending && onClose()}>
      <AlertDialogContent>
        <AlertDialogHeader>
          <AlertDialogTitle>Delete {setting.name}?</AlertDialogTitle>
          <AlertDialogDescription>
            {SCOPE_LABEL[setting.scope]} restart without it.
            {setting.secret ? ' The secret value cannot be recovered.' : ''}
          </AlertDialogDescription>
        </AlertDialogHeader>
        <AlertDialogFooter>
          <AlertDialogCancel disabled={del.isPending}>Cancel</AlertDialogCancel>
          <AlertDialogAction
            onClick={(e) => {
              e.preventDefault()
              onDelete()
            }}
            disabled={del.isPending}
            className="bg-destructive hover:bg-destructive/90 text-white"
          >
            {del.isPending && <Loader2 className="h-4 w-4 animate-spin" />}
            Delete
          </AlertDialogAction>
        </AlertDialogFooter>
      </AlertDialogContent>
    </AlertDialog>
  )
}

/**
 * Environment tab: the publisher's settings and secrets for the app's branch and preview
 * instances, and what Vetra sets on every instance. Owners and operators only; the API refuses
 * anyone else, which is shown as such.
 */
export function AppEnvironment({
  appId,
  instancesEnabled,
}: {
  appId: string
  instancesEnabled: boolean
}) {
  const query = useAppSettings(appId)
  const [editing, setEditing] = useState<Editing | null>(null)
  const [deleting, setDeleting] = useState<AppSetting | null>(null)

  if (query.isPending) {
    return (
      <div className="space-y-6" aria-busy aria-label="Loading environment settings">
        <Skeleton className="h-48 w-full rounded-2xl" />
        <Skeleton className="h-32 w-full rounded-2xl" />
      </div>
    )
  }

  if (query.error || !query.data) {
    const forbidden = isAppsError(query.error, 'FORBIDDEN')
    const unavailable = isAppsError(query.error, 'APPS_UNAVAILABLE')
    return (
      <div className="bg-card border-border flex flex-col items-center gap-3 rounded-2xl border p-8 text-center shadow-sm">
        <ShieldAlert className="text-muted-foreground h-6 w-6" aria-hidden />
        <p className="font-semibold">
          {forbidden
            ? 'Only the app’s owners and operators manage its environment'
            : 'Environment settings did not load'}
        </p>
        <p className="text-muted-foreground max-w-md text-sm">
          {forbidden
            ? 'Ask an owner of this app for access.'
            : unavailable
              ? 'Environment settings are not available on this server yet.'
              : describeAppsError(query.error)}
        </p>
        {!forbidden && !unavailable && (
          <Button
            variant="outline"
            size="sm"
            onClick={() => void query.refetch()}
            disabled={query.isRefetching}
          >
            <RefreshCw className={query.isRefetching ? 'h-4 w-4 animate-spin' : 'h-4 w-4'} />
            Try again
          </Button>
        )}
      </div>
    )
  }

  const data = query.data
  const full = data.settings.length >= MAX_SETTINGS_PER_APP

  return (
    <div className="space-y-6">
      <SettingsCard
        title="Environment settings"
        description={
          <>
            Plain settings and secrets for this app&apos;s branch and preview instances, set once
            for the app. A change restarts the instances it applies to; production is not affected.
            {!instancesEnabled &&
              ' Branch instances are off for this app; turn them on in Settings.'}
          </>
        }
        footer={
          <>
            {full && (
              <span className="text-muted-foreground mr-auto text-xs">
                At most {MAX_SETTINGS_PER_APP} settings; delete one to add another.
              </span>
            )}
            <Button onClick={() => setEditing({ mode: 'add' })} disabled={full}>
              <Plus className="h-4 w-4" />
              Add setting
            </Button>
          </>
        }
      >
        <p className="border-warning/40 bg-warning/10 flex items-start gap-2 rounded-lg border px-3 py-2 text-xs">
          <Lock className="text-warning mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
          <span>
            Plain values are visible in Vetra&apos;s deployment repository. Use a secret for
            anything sensitive: secrets are stored encrypted and never shown again.
          </span>
        </p>
        {data.settings.length === 0 ? (
          <p className="text-muted-foreground border-border rounded-xl border border-dashed px-4 py-6 text-center text-sm">
            No settings yet. Add the values your app reads from its environment.
          </p>
        ) : (
          <ul className="border-border divide-border divide-y overflow-hidden rounded-xl border">
            {data.settings.map((s) => (
              <SettingRow
                key={`${s.name}-${s.scope}`}
                setting={s}
                onReplace={() => setEditing({ mode: 'replace', setting: s })}
                onDelete={() => setDeleting(s)}
              />
            ))}
          </ul>
        )}
      </SettingsCard>

      <SettingsCard
        title="Set by Vetra"
        description="Every instance gets these. They cannot be set or overridden."
      >
        <ul className="border-border divide-border divide-y overflow-hidden rounded-xl border">
          {data.vetra.map((s) => (
            <VetraRow key={s.name} setting={s} />
          ))}
        </ul>
      </SettingsCard>

      {editing && (
        <SettingDialog
          key={
            editing.mode === 'replace' ? `${editing.setting.name}-${editing.setting.scope}` : 'add'
          }
          appId={appId}
          editing={editing}
          data={data}
          onClose={() => setEditing(null)}
        />
      )}
      {deleting && (
        <DeleteSettingDialog appId={appId} setting={deleting} onClose={() => setDeleting(null)} />
      )}
    </div>
  )
}
