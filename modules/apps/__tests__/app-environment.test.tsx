import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'

import { AppsApiError } from '../graphql'
import type { AppSetting, AppSettings } from '../types'

type QueryState = { data: AppSettings | undefined; isPending: boolean; error: Error | null }
let state: QueryState
const setMutate = vi.fn()
const deleteMutate = vi.fn()

vi.mock('sonner', () => ({ toast: { success: vi.fn(), error: vi.fn() } }))
vi.mock('../hooks/use-apps', () => ({
  useAppSettings: () => ({ ...state, refetch: vi.fn(), isRefetching: false }),
  useSetAppSetting: () => ({ mutate: setMutate, isPending: false }),
  useDeleteAppSetting: () => ({ mutate: deleteMutate, isPending: false }),
}))
// Renown profile names: the person component resolves an address to a name.
vi.mock('@/modules/shared/components/person-name', () => ({
  PersonName: ({ value }: { value: string }) => (
    <span>{value === '0xfrank' ? 'Frank' : 'someone'}</span>
  ),
}))
// app-settings pulls in org and GitHub hooks; only its card is used here.
vi.mock('../components/app-settings', () => ({
  SettingsCard: ({
    title,
    description,
    children,
    footer,
  }: {
    title: string
    description?: React.ReactNode
    children: React.ReactNode
    footer?: React.ReactNode
  }) => (
    <section aria-label={title}>
      <h3>{title}</h3>
      <div>{description}</div>
      {children}
      {footer}
    </section>
  ),
}))

import { AppEnvironment } from '../components/app-environment'

const recent = new Date(Date.now() - 3 * 86_400_000).toISOString()

function setting(over: Partial<AppSetting> = {}): AppSetting {
  return {
    name: 'API_URL',
    scope: 'ALL',
    secret: false,
    value: 'https://api.example.com',
    updatedAt: recent,
    updatedBy: '0xfrank',
    ...over,
  }
}

function data(settings: AppSetting[] = []): AppSettings {
  return {
    settings,
    vetra: [
      { name: 'PH_HOST', secret: false, value: 'the release’s host (e.g. cli)' },
      {
        name: 'PH_WORKFLOWS_SECRETS_MASTER_KEY',
        secret: true,
        value: 'generated once per instance, kept in OpenBao',
      },
    ],
    reservedNames: ['PH_HOST', 'ADMINS'],
    reservedPrefixes: ['VETRA_', 'NODE_', 'PG'],
  }
}

const renderTab = () => render(<AppEnvironment appId="a1" instancesEnabled />)

describe('AppEnvironment', () => {
  beforeEach(() => {
    cleanup()
    setMutate.mockReset()
    deleteMutate.mockReset()
    state = {
      data: data([
        setting(),
        setting({ name: 'API_KEY', secret: true, value: null, scope: 'BRANCH' }),
      ]),
      isPending: false,
      error: null,
    }
  })

  it('lists plain values and secrets with who set them, by Renown name', () => {
    renderTab()
    const plain = screen.getByTestId('setting-API_URL-ALL')
    expect(plain.textContent).toContain('https://api.example.com')
    expect(plain.textContent).toContain('All instances')
    expect(plain.textContent).toMatch(/set 3 days ago by Frank/)
    const secret = screen.getByTestId('setting-API_KEY-BRANCH')
    expect(secret.textContent).toMatch(/secret ·\s*set 3 days ago by Frank/)
    expect(secret.textContent).toContain('Branch instances')
    expect(screen.queryByText(/0xfrank/)).toBeNull()
  })

  it('shows what Vetra sets, secrets as generated by Vetra', () => {
    renderTab()
    expect(screen.getByTestId('vetra-PH_HOST').textContent).toContain('the release’s host')
    expect(screen.getByTestId('vetra-PH_WORKFLOWS_SECRETS_MASTER_KEY').textContent).toContain(
      'generated by Vetra',
    )
  })

  it('warns that plain values are visible in the deployment repository', () => {
    renderTab()
    expect(
      screen.getByText(/Plain values are visible in Vetra.s deployment repository/),
    ).toBeTruthy()
  })

  it('refuses reserved and malformed names before calling the API', () => {
    renderTab()
    fireEvent.click(screen.getByRole('button', { name: /Add setting/ }))
    const name = screen.getByLabelText('Name')
    fireEvent.change(name, { target: { value: 'ADMINS' } })
    expect(screen.getByText('ADMINS is set by Vetra; it cannot be set.')).toBeTruthy()
    fireEvent.change(name, { target: { value: 'VETRA_X' } })
    expect(screen.getByText('Names starting with VETRA_ are reserved for Vetra.')).toBeTruthy()
    fireEvent.change(name, { target: { value: 'lower' } })
    expect(screen.getByText(/Use capitals, digits and _/)).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Add setting' }))
    expect(setMutate).not.toHaveBeenCalled()
  })

  it('adds a secret through a password field, with the chosen scope', () => {
    renderTab()
    fireEvent.click(screen.getByRole('button', { name: /Add setting/ }))
    fireEvent.change(screen.getByLabelText('Name'), { target: { value: 'STRIPE_KEY' } })
    fireEvent.click(screen.getByRole('switch', { name: 'Secret' }))
    const value = screen.getByLabelText('Secret value')
    expect(value.getAttribute('type')).toBe('password')
    fireEvent.change(value, { target: { value: 'sk_live_1' } })
    fireEvent.click(screen.getByRole('radio', { name: /Preview instances/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Add setting' }))
    expect(setMutate).toHaveBeenCalledWith(
      { name: 'STRIPE_KEY', value: 'sk_live_1', secret: true, scope: 'PREVIEW' },
      expect.anything(),
    )
  })

  it('replaces a secret with an empty, write-only field and a fixed name and scope', () => {
    renderTab()
    const row = screen.getByTestId('setting-API_KEY-BRANCH')
    fireEvent.click(within(row).getByRole('button', { name: /Replace/ }))
    expect(screen.getByLabelText<HTMLInputElement>('Name').disabled).toBe(true)
    const value = screen.getByLabelText<HTMLInputElement>('Secret value')
    expect(value.type).toBe('password')
    expect(value.value).toBe('')
    fireEvent.click(screen.getByRole('button', { name: 'Replace' }))
    expect(screen.getByText('Enter the secret value.')).toBeTruthy()
    expect(setMutate).not.toHaveBeenCalled()
    fireEvent.change(value, { target: { value: 'new' } })
    fireEvent.click(screen.getByRole('button', { name: 'Replace' }))
    expect(setMutate).toHaveBeenCalledWith(
      { name: 'API_KEY', value: 'new', secret: true, scope: 'BRANCH' },
      expect.anything(),
    )
  })

  it('prefills a plain value when replacing it', () => {
    renderTab()
    fireEvent.click(
      within(screen.getByTestId('setting-API_URL-ALL')).getByRole('button', { name: /Replace/ }),
    )
    expect(screen.getByLabelText<HTMLInputElement>('Value').value).toBe('https://api.example.com')
  })

  it('shows the server error in the dialog', () => {
    setMutate.mockImplementation((_v, opts: { onError: (e: Error) => void }) =>
      opts.onError(new AppsApiError('SERVICE_UNAVAILABLE', 'Secret storage unavailable')),
    )
    renderTab()
    fireEvent.click(screen.getByRole('button', { name: /Add setting/ }))
    fireEvent.change(screen.getByLabelText('Name'), { target: { value: 'TOKEN' } })
    fireEvent.click(screen.getByRole('switch', { name: 'Secret' }))
    fireEvent.change(screen.getByLabelText('Secret value'), { target: { value: 'x' } })
    fireEvent.click(screen.getByRole('button', { name: 'Add setting' }))
    expect(screen.getByRole('alert').textContent).toBe('Secret storage unavailable')
  })

  it('deletes only after confirming', () => {
    renderTab()
    fireEvent.click(screen.getByRole('button', { name: 'Delete API_KEY (branch instances)' }))
    expect(deleteMutate).not.toHaveBeenCalled()
    expect(screen.getByText('Delete API_KEY?')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Delete' }))
    expect(deleteMutate).toHaveBeenCalledWith(
      { name: 'API_KEY', scope: 'BRANCH' },
      expect.anything(),
    )
  })

  it('tells someone who is not an operator that the environment is not theirs to manage', () => {
    state = {
      data: undefined,
      isPending: false,
      error: new AppsApiError('FORBIDDEN', 'Not allowed to manage this App'),
    }
    renderTab()
    expect(screen.getByText(/Only the app.s owners, operators and release managers/)).toBeTruthy()
    expect(screen.queryByRole('button', { name: /Try again/ })).toBeNull()
  })

  it('shows an empty state', () => {
    state.data = data([])
    renderTab()
    expect(screen.getByText(/No settings yet/)).toBeTruthy()
  })
})
